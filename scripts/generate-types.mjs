import { writeFile } from 'node:fs/promises';
import { migratedDatabase, root } from '../tests/helpers.mjs';

// Introspect the fully migrated PostgreSQL catalog, rather than maintaining
// a second hand-written schema. `supabase gen types typescript --local` is
// also supported after starting the real Supabase stack.
const db = await migratedDatabase();
const { rows: columns } = await db.query(`select table_name, column_name, is_nullable,
  column_default, udt_name from information_schema.columns where table_schema = 'public' and table_name = any(private.pos_tables())
  order by table_name, ordinal_position`);
const { rows: fks } = await db.query(`select c.conname, c.conrelid::regclass::text as source,
  c.confrelid::regclass::text as target,
  exists (select 1 from pg_constraint u where u.conrelid=c.conrelid
    and u.contype in ('p','u') and u.conkey <@ c.conkey) as one_to_one,
  array(select a.attname from unnest(c.conkey) with ordinality k(n,i) join pg_attribute a
    on a.attrelid=c.conrelid and a.attnum=k.n order by k.i) as columns,
  array(select a.attname from unnest(c.confkey) with ordinality k(n,i) join pg_attribute a
    on a.attrelid=c.confrelid and a.attnum=k.n order by k.i) as referenced_columns
  from pg_constraint c join pg_namespace n on n.oid=c.connamespace
  where c.contype='f' and n.nspname='public' order by c.conname`);
const { rows: functions } = await db.query(`select p.proname, p.proargnames as names,
  array(select t.typname from unnest(p.proargtypes::oid[]) with ordinality a(n,i)
    join pg_type t on t.oid=a.n order by a.i) as types,
  p.pronargdefaults as defaults, t.typname as result
  from pg_proc p join pg_namespace n on n.oid=p.pronamespace join pg_type t on t.oid=p.prorettype
  where n.nspname='public' order by p.proname`);
const { rows: enums } = await db.query(`select t.typname, array_agg(e.enumlabel order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid=t.oid join pg_namespace n on n.oid=t.typnamespace
  where n.nspname='public' group by t.typname`);
function type(name, nullable = false) {
  const array = name.startsWith('_');
  const scalar = array ? name.slice(1) : name;
  const base = scalar === 'jsonb' || scalar === 'json' ? 'Json' : scalar === 'bool' ? 'boolean'
    : /^(numeric|int[248]|float[48])$/.test(scalar) ? 'number' : scalar === 'void' ? 'undefined'
    : scalar === 'app_role' ? 'Database["public"]["Enums"]["app_role"]' : 'string';
  return (array ? `(${base})[]` : base) + (nullable ? ' | null' : '');
}
let out = '// Generated by npm run types from the ordered SQL migrations. Do not edit.\n';
out += 'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\n';
out += 'export type Database = {\n  public: {\n    Tables: {\n';
for (const table of [...new Set(columns.map(c => c.table_name))]) {
  const cols = columns.filter(c => c.table_name === table);
  out += `      ${table}: {\n`;
  for (const mode of ['Row', 'Insert', 'Update']) {
    out += `        ${mode}: {\n`;
    for (const c of cols) {
      const optional = mode === 'Update' || mode === 'Insert' && (c.column_default !== null || c.is_nullable === 'YES');
      out += `          ${c.column_name}${optional ? '?' : ''}: ${type(c.udt_name, c.is_nullable === 'YES')};\n`;
    }
    out += '        };\n';
  }
  out += '        Relationships: [\n';
  for (const fk of fks.filter(f => f.source.replace('public.', '') === table && f.target !== 'auth.users')) {
    out += `          { foreignKeyName: ${JSON.stringify(fk.conname)}; columns: ${JSON.stringify(fk.columns)}; isOneToOne: ${fk.one_to_one}; referencedRelation: ${JSON.stringify(fk.target.replace('public.', ''))}; referencedColumns: ${JSON.stringify(fk.referenced_columns)} },\n`;
  }
  out += '        ];\n      };\n';
}
out += '    };\n    Views: Record<string, never>;\n    Functions: {\n';
for (const f of functions) {
  out += `      ${f.proname}: { Args: { `;
  f.names?.forEach((name, i) => {
    const optional = i >= f.types.length - Number(f.defaults || 0);
    const nullable = ['p_customer_id', 'p_promotion_code','p_product_id','p_recipe_id','p_category_id','p_description','p_photo_url',
      'p_output_unit_id','p_unit_id','p_location_id','p_destination_location_id','p_expected_revision'].includes(name)
      || name === 'p_outlet_id' && ['set_member', 'post_journal'].includes(f.proname);
    out += `${name}${optional ? '?' : ''}: ${type(f.types[i], nullable)}; `;
  });
  out += `}; Returns: ${type(f.result)} };\n`;
}
out += '    };\n    Enums: {\n';
for (const e of enums) out += `      ${e.typname}: ${e.labels.map(x => JSON.stringify(x)).join(' | ')};\n`;
out += '    };\n    CompositeTypes: Record<string, never>;\n  };\n};\n';
await writeFile(new URL('frontend/src/lib/database.types.ts', root), out);
await db.close();
console.log(`Generated ${new Set(columns.map(c => c.table_name)).size} tables and ${functions.length} RPC types.`);
